"""Provide the configured GitHub token through Git's credential protocol."""

import json
import logging
import os
import shlex
import subprocess
import sys
from pathlib import Path

logger = logging.getLogger(__name__)
_HELPER_KEY = "credential.https://github.com.helper"
_LEGACY_URL = r"^url\.https://oauth2:.*@github\.com/\.insteadof$"


def resolve_github_token(settings: dict) -> str:
    keys = settings.get("api_keys")
    saved_key = keys.get("github") if isinstance(keys, dict) else None
    candidates = (
        [item.get("api_key") for item in settings.get("custom_providers") or []
         if isinstance(item, dict) and item.get("id") == "github"]
        + [saved_key, os.environ.get("GITHUB_API_KEY"),
           os.environ.get("GITHUB_TOKEN")]
    )
    return next((value for value in candidates if isinstance(value, str) and value
                 and not any(char in value for char in "\r\n\0")), "")


def _settings(path: Path) -> dict:
    try:
        settings = json.loads(path.read_text(encoding="utf-8"))
        return settings if isinstance(settings, dict) else {}
    except (OSError, ValueError):
        return {}


def _git_config(*args: str, missing: tuple[int, ...] = ()) -> str:
    result = subprocess.run(
        ["git", "config", "--global", *args],
        check=False, capture_output=True, text=True, timeout=10,
    )
    if result.returncode and result.returncode not in missing:
        raise OSError(f"git config exited with code {result.returncode}")
    return result.stdout


def configure_github_credentials(settings_path: Path) -> None:
    try:
        # Remove only the rewrite entries generated by prior versions of AuroraCoder.
        legacy = _git_config("--null", "--get-regexp", _LEGACY_URL, missing=(1,))
        for item in legacy.split("\0"):
            key, _, value = item.partition("\n")
            if key and value == "https://github.com/":
                _git_config("--fixed-value", "--unset-all", key, value, missing=(5,))
        if not resolve_github_token(_settings(settings_path)):
            return

        command = "!" + " ".join(shlex.quote(path.as_posix()) for path in (
            Path(sys.executable), Path(__file__).resolve(), settings_path.resolve(),
        ))
        configured = _git_config("--get-all", _HELPER_KEY, missing=(1,)).splitlines()
        if command not in configured:
            _git_config("--add", _HELPER_KEY, command)
    except (OSError, subprocess.SubprocessError):
        logger.warning("Could not configure the GitHub credential helper")


def _serve_credentials(settings_path: Path) -> None:
    fields = dict(line.rstrip("\r\n").split("=", 1) for line in sys.stdin if "=" in line)
    if fields.get("protocol", "").strip() != "https" or fields.get("host", "").strip() != "github.com":
        return
    token = resolve_github_token(_settings(settings_path))
    if token:
        print(f"username=oauth2\npassword={token}\n")


if __name__ == "__main__":
    settings_path = Path(sys.argv[1])
    operation = sys.argv[2]
    if operation == "configure":
        configure_github_credentials(settings_path)
    elif operation == "get":
        _serve_credentials(settings_path)
